#!/usr/bin/env bash
# Generate plugin skills from the template's embedded skills (ADR-009).
#
# The template under skills/lloydbriantech-ascent/assets/template/ is the single
# source of truth (CLAUDE.md architecture rule 1). Plugin copies are BUILT from
# it, never edited: this script rewrites names, links and placeholders so the
# skills read correctly outside a scaffolded project, and stamps each copy with
# a "generated" notice. `make test-plugins` fails if a committed copy drifts
# from what this script produces.
#
# Usage: build-plugins.sh [OUT_ROOT]   (OUT_ROOT defaults to the repo root;
#        the plugin is written to OUT_ROOT/plugins/<plugin>/skills/)
#
# When building into the repo root, it also records each plugin's version and
# content hash in make/plugins.lock (plugin<TAB>version<TAB>sha256). A row is
# written only when it is missing or the version changed. If the content changed
# under an unchanged version, the lock is left alone and a warning asks for a
# version bump; `make test-plugins` T10 fails until the version is bumped.
# Portable: GNU/Linux and BSD/macOS, bash 3.2+.

set -euo pipefail

case "${1:-}" in -h|--help) sed -n '2,/^$/s/^# \{0,1\}//p' "$0"; exit 0 ;; esac

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_ROOT="${1:-$REPO_ROOT}"
SRC="skills/lloydbriantech-ascent/assets/template/.claude/skills"

# plugin|source-skill|plugin-skill   (one row per generated skill)
MAP="ascent-security|ascent-env-audit|env-audit
ascent-security|ascent-security-audit|security-audit
ascent-security|ascent-sec-posture|sec-posture"

plugin_version() {  # read "version" from the plugin's committed manifest
  sed -n 's/^[[:space:]]*"version":[[:space:]]*"\([^"]*\)".*/\1/p' \
    "$REPO_ROOT/plugins/$1/.claude-plugin/plugin.json" | head -1
}

SED="$(mktemp)"
trap 'rm -f "$SED"' EXIT

# Remove previously generated skills first, so a row deleted from MAP cannot
# leave an orphan behind. Only folders carrying the GENERATED marker are touched.
if [ -d "$OUT_ROOT/plugins" ]; then
  grep -rl '^<!-- GENERATED by make plugins' "$OUT_ROOT/plugins" 2>/dev/null | while IFS= read -r g; do
    rm -f "$g"; rmdir "$(dirname "$g")" 2>/dev/null || true
  done
fi

printf '%s\n' "$MAP" | while IFS='|' read -r plugin src dst; do
  version="$(plugin_version "$plugin")"
  [ -n "$version" ] || { echo "build-plugins: no version in plugins/$plugin/.claude-plugin/plugin.json" >&2; exit 1; }

  # Links and names for skills in the same plugin become plugin-local; links to
  # any other ascent-* skill become plain text, because that skill is not here.
  {
    printf 's|^name: %s$|name: %s|\n' "$src" "$dst"
    printf 's|^version: <<PROJECT_VERSION>>$|version: %s|\n' "$version"
    printf '%s\n' "$MAP" | while IFS='|' read -r p s d; do
      [ "$p" = "$plugin" ] || continue
      printf 's|\\[%s\\](\\.\\./%s/SKILL\\.md\\([^)]*\\))|[%s](../%s/SKILL.md\\1)|g\n' "$s" "$s" "$d" "$d"
    done
    printf 's|\\[\\(ascent-[a-zA-Z0-9-]*\\)\\](\\.\\./ascent-[a-zA-Z0-9-]*/SKILL\\.md[^)]*)|`\\1` (an ASCENT project skill)|g\n'
    printf 's|<<PROJECT_TITLE>>'"'"'s|the project'"'"'s|g\n'
    printf 's|<<PROJECT_TITLE>>|the project|g\n'
    printf 's|<<ENV_PREFIX>>|APP|g\n'
  } > "$SED"

  # Bare skill names, whole words only (perl lookarounds; BSD sed has no \b).
  NAMES=$(printf '%s\n' "$MAP" | awk -F'|' -v p="$plugin" '$1 == p { printf "%s=%s ", $2, $3 }')
  out_dir="$OUT_ROOT/plugins/$plugin/skills/$dst"
  mkdir -p "$out_dir"
  sed -f "$SED" "$REPO_ROOT/$SRC/$src/SKILL.md" \
    | NAMES="$NAMES" perl -pe 'BEGIN { for (split / /, $ENV{NAMES}) { my ($s, $d) = split /=/; push @m, [$s, $d] } } for my $x (@m) { my ($s, $d) = @$x; s/(?<![\w-])\Q$s\E(?![\w-])/$d/g }' \
    | awk -v src="$SRC/$src/SKILL.md" '
        { print }
        /^---$/ && ++fences == 2 {
          print ""
          print "<!-- GENERATED by make plugins from " src " — edit the source, not this file. -->"
        }' > "$out_dir/SKILL.md"

  if grep -qE '<<[A-Z_]+>>' "$out_dir/SKILL.md"; then
    echo "build-plugins: placeholders survived in $out_dir/SKILL.md:" >&2
    grep -nE '<<[A-Z_]+>>' "$out_dir/SKILL.md" >&2
    exit 1
  fi
  echo "build-plugins: $plugin/$dst <- $src (v$version)"
done

# Version lock (T10). Only for a build into the repository itself: T1 builds
# into a temporary OUT_ROOT and must not touch the lock.
if [ "$(cd "$OUT_ROOT" && pwd)" = "$REPO_ROOT" ]; then
  LOCK="$REPO_ROOT/make/plugins.lock"
  TAB="$(printf '\t')"
  [ -f "$LOCK" ] || printf '# plugin\tversion\tsha256 — written by make plugins; see make/test-plugins.sh T10\n' > "$LOCK"
  for pj in "$REPO_ROOT"/plugins/*/.claude-plugin/plugin.json; do
    [ -f "$pj" ] || continue
    plugin="$(basename "$(dirname "$(dirname "$pj")")")"
    version="$(plugin_version "$plugin")"
    hash="$(bash "$REPO_ROOT/make/plugin-hash.sh" "$REPO_ROOT/plugins/$plugin")"
    row="$(awk -F'\t' -v p="$plugin" '$1 == p { print; exit }' "$LOCK")"
    lock_ver="$(printf '%s' "$row" | cut -f2)"
    lock_hash="$(printf '%s' "$row" | cut -f3)"
    if [ -z "$row" ] || [ "$lock_ver" != "$version" ]; then
      awk -F'\t' -v p="$plugin" '$1 != p' "$LOCK" > "$LOCK.tmp"
      printf '%s%s%s%s%s\n' "$plugin" "$TAB" "$version" "$TAB" "$hash" >> "$LOCK.tmp"
      mv "$LOCK.tmp" "$LOCK"
      echo "build-plugins: plugins.lock records $plugin v$version"
    elif [ "$lock_hash" != "$hash" ]; then
      echo "build-plugins: WARNING $plugin: content changed under $version; bump plugins/$plugin/.claude-plugin/plugin.json version and the marketplace entry" >&2
    fi
  done
fi
