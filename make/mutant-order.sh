#!/usr/bin/env bash
# The order file of the negative controls (ADR-029).
#
# make/mutant-order.tsv holds, for each T11 control, the behavior test that caught
# it in fast mode last time: make test-mutants runs that test first next time
# (ASCENT_T11_LEAD, make/test-plugins.sh). Any failing test fails T11, so the file
# orders tests and never changes a verdict; a missing, stale or damaged row costs
# time only. Rows are "<id><TAB><test>", the test's file name without .sh; lines
# starting with # are comments. For an id with several rows, the first one counts.
#
# Usage: mutant-order.sh caught GATE-OUTPUT
#          prints the test the gate's first T11 FAIL line names first as
#          "<test> failed:", or nothing when it names none (a problem such as a
#          script no test exercises, or a test that printed FAIL lines but exited 0,
#          is not a catching test)
#        mutant-order.sh merge TIMES ORDER IDS
#          prints ORDER merged with TIMES (make test-mutants TIMES=<file>, seven
#          columns, the last "caught by"): a control TIMES shows killed with a
#          catching test gets that row; every other row is kept; rows whose id is not
#          in IDS (one id per line) are dropped. Exit 2 on a times file without the
#          "caught by" column
#        mutant-order.sh count ORDER MANIFEST ROOT [all]
#          prints "<led> <t11> <stale>" over MANIFEST's T11 controls (test-mutants.sh
#          --list): <led> have a row whose test exists under ROOT/tests/plugins/<the
#          control's T11 scope>/ (any plugin's, for the scope all); <stale> rows name
#          a test that does not exist, or are malformed; with all, the rows of
#          controls not in MANIFEST are stale too. Always exits 0
#        mutant-order.sh write TIMES
#          merges TIMES into make/mutant-order.tsv, with the controls make
#          test-mutants --list has today (make mutant-order FROM=<times file>)
# Portable: GNU/Linux and BSD/macOS, bash 3.2+, any POSIX awk.

set -euo pipefail
case "${1:-}" in -h|--help) sed -n '2,/^$/s/^# \{0,1\}//p' "$0"; exit 0 ;; esac

HERE="$(cd "$(dirname "$0")" && pwd)"
usage() { echo "mutant-order: usage: $1 (mutant-order.sh --help)" >&2; exit 2; }

# The header comment of the order file
header() {
  printf '%s\n' '# Generated by make mutant-order FROM=<times file> (ADR-029): the test file that caught' \
    '# each T11 control in fast mode, run first next time. It orders tests; it never changes a verdict.'
}

caught() {
  [ -f "$1" ] || return 0
  # The text up to the end of the first "<test> failed:", without what comes before
  # the test's name: match() finds the leftmost
  awk '/^FAIL  test-plugins: T11 / {
    if (match($0, / test-[A-Za-z0-9_-]+ failed:/)) { s = substr($0, 1, RSTART + RLENGTH - 9); sub(/.* /, "", s); print s }
    exit
  }' "$1"
}

merge() {
  local times=$1 order=$2 ids=$3
  [ -f "$order" ] || order=/dev/null
  if ! awk -F'\t' 'NR == 1 { sub(/\r$/, ""); ok = (NF == 7 && $7 == "caught by"); exit } END { exit !ok }' "$times" 2>/dev/null; then
    echo "mutant-order: $times is not a times file with a \"caught by\" column (make test-mutants TIMES=<file>, v0.4.25 or later)" >&2
    exit 2
  fi
  header
  awk -F'\t' -v ids="$ids" -v order="$order" '
    { sub(/\r$/, "") }
    FILENAME == ids { if ($0 != "") want[$0] = 1; next }
    FILENAME == order { if (/^#/ || NF != 2 || $1 == "" || $2 == "") next; if (!($1 in row)) row[$1] = $2; next }
    FNR == 1 { next }
    $2 == "killed" && $7 != "" && !($3 in got) { got[$3] = $7 }
    END { for (k in got) row[k] = got[k]; for (k in row) if (k in want) print k "\t" row[k] }
  ' "$ids" "$order" "$times" | LC_ALL=C sort
}

count() {
  local order=$1 manifest=$2 root=$3 all=${4:-}
  [ -f "$order" ] || order=/dev/null
  # The behavior tests that exist, "<plugin> <test>" per line
  ( cd "$root/tests/plugins" 2>/dev/null && for f in */*.sh; do [ -f "$f" ] && echo "${f%%/*} $(basename "$f" .sh)"; done ) > "$WORK/tests" || true
  awk -F'\t' -v tests="$WORK/tests" -v manifest="$manifest" -v order="$order" -v all="$all" '
    { sub(/\r$/, "") }
    FILENAME == tests { split($0, a, " "); has[a[1], a[2]] = 1; anyp[a[2]] = 1; next }
    FILENAME == manifest { if ($3 == "T11" && !($2 in scope)) { scope[$2] = $6; t11++ }; next }
    /^#/ || $0 == "" { next }
    NF != 2 || $1 == "" || $2 == "" { stale++; next }
    $1 in seen { next }
    { seen[$1] = 1
      if (!($1 in scope)) { if (all == "all") stale++; next }
      n = split(scope[$1], ps, " "); found = 0
      for (i = 1; i <= n; i++) if ((ps[i] == "all" && ($2 in anyp)) || ((ps[i], $2) in has)) found = 1
      if (found) led++; else stale++ }
    END { print led + 0, t11 + 0, stale + 0 }
  ' "$WORK/tests" "$manifest" "$order"
}

write() {
  local times=$1 root ord tmp old
  root="$(cd "$HERE/.." && pwd)"; ord="$root/make/mutant-order.tsv"
  ASCENT_MUTANT_GROUP= ASCENT_MUTANT_IDS= ASCENT_MUTANT_MODE= bash "$root/make/test-mutants.sh" --list \
    | awk -F'\t' '$3 == "T11" { print $2 }' > "$WORK/ids"
  tmp=$(mktemp "$ord.XXXXXX")
  ( merge "$times" "$ord" "$WORK/ids" ) > "$tmp" || { rm -f "$tmp"; exit 2; }
  old=$ord; [ -f "$old" ] || old=/dev/null
  # What changed: rows added or replaced, and rows removed
  set -- $(awk -F'\t' -v old="$old" '
    /^#/ || NF != 2 { next }
    FILENAME == old { if (!($1 in o)) o[$1] = $2; next }
    { n++; if (!($1 in o) || o[$1] != $2) r++; keep[$1] = 1 }
    END { for (k in o) if (!(k in keep)) d++; print n + 0, r + 0, d + 0 }
  ' "$old" "$tmp")
  chmod 644 "$tmp"; mv "$tmp" "$ord"
  echo "make/mutant-order.tsv: $1 rows ($2 replaced or added, $3 removed)"
}

WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
cmd=${1:-}; [ $# -eq 0 ] || shift
case "$cmd" in
  caught) [ $# -eq 1 ] || usage "caught GATE-OUTPUT"; caught "$1" ;;
  merge)  [ $# -eq 3 ] || usage "merge TIMES ORDER IDS"; merge "$@" ;;
  count)  [ $# -eq 3 ] || [ $# -eq 4 ] || usage "count ORDER MANIFEST ROOT [all]"; count "$@" ;;
  write)  [ $# -eq 1 ] && [ -n "$1" ] || usage "write TIMES, or make mutant-order FROM=<times file>"
          [ -f "$1" ] || { echo "mutant-order: no times file $1" >&2; exit 2; }; write "$1" ;;
  *) usage "caught|merge|count|write …" ;;
esac
