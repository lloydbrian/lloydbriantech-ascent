#!/usr/bin/env bash
# Turn Design Tokens JSON (format 2025.10) into CSS custom properties. Part of the
# ascent-ux plugin (design-directions Step 3: the mock sheet for each direction).
# Read-only: prints to standard output.
#
# Usage: tokens-to-css.sh LIGHT.tokens.json [DARK.tokens.json]
#
# Output: a ":root" block with every light token, and, when a dark file is given,
# the dark values twice: under @media (prefers-color-scheme: dark) for
# ":root:not([data-theme=light])", and under ":root[data-theme=dark]", so a page
# follows the system setting and can still be switched by hand. Names are token
# paths joined with "-" ("color.text.primary" -> --color-text-primary). Aliases are
# resolved to values. cubicBezier tokens become cubic-bezier(...). Only tokens whose
# value differs from the light file appear in the dark blocks.
# Exit: 0 written; 2 bad input (unreadable JSON, unresolvable alias, unsupported value).
# Portable: GNU/Linux and BSD/macOS, bash 3.2+, POSIX awk (run with LC_ALL=C, so
# positions and lengths are bytes in every awk and invalid UTF-8 cannot stop it).

set -euo pipefail

case "${1:-}" in -h|--help) sed -n '2,/^$/s/^# \{0,1\}//p' "$0"; exit 0 ;; esac

HERE="$(cd "$(dirname "$0")" && pwd)"
LIB="$HERE/lib/tokens.awk"
[ -f "$LIB" ] || { echo "tokens-to-css: missing $LIB" >&2; exit 2; }
{ [ $# -eq 1 ] || [ $# -eq 2 ]; } || { sed -n '6p' "$0" | sed 's/^# //' >&2; exit 2; }
for f in "$@"; do
  [ -f "$f" ] || { echo "tokens-to-css: no such file: $f" >&2; exit 2; }
  case "$f" in *.json) ;; *) echo "tokens-to-css: not a JSON file: $f" >&2; exit 2 ;; esac
done

PROG="$(cat "$LIB")"'
function slurp(path,   line, s) { s = ""; while ((getline line < path) > 0) s = s line "\n"; close(path); return s }
function css(theme, nm,   v) {
  v = resolve(theme, nm)
  if (RESERR != "") { printf "tokens-to-css: %s: %s\n", theme, RESERR > "/dev/stderr"; exit 2 }
  if (T[theme, nm] == "cubicBezier" || T["light", nm] == "cubicBezier") v = "cubic-bezier(" v ")"
  return v
}
BEGIN {
  TOKERR = ""
  if (!json_load(slurp(ENVIRON["ASCENT_LIGHT"]), "light")) { print "tokens-to-css: cannot read " ENVIRON["ASCENT_LIGHT"] ": " TOKERR > "/dev/stderr"; exit 2 }
  if (ENVIRON["ASCENT_DARK"] != "" && !json_load(slurp(ENVIRON["ASCENT_DARK"]), "dark")) { print "tokens-to-css: cannot read " ENVIRON["ASCENT_DARK"] ": " TOKERR > "/dev/stderr"; exit 2 }
  n = split(NAMES["light"], L, " ")
  print "/* generated by ascent-ux tokens-to-css.sh; edit the token files, not this sheet */"
  print ":root {"
  for (i = 1; i <= n; i++) printf "  --%s: %s;\n", L[i], css("light", L[i])
  print "}"
  if (ENVIRON["ASCENT_DARK"] == "") exit 0
  m = split(NAMES["dark"], D, " "); out = ""
  for (i = 1; i <= m; i++) { v = css("dark", D[i]); if (!(("light", D[i]) in V) || v != css("light", D[i])) out = out sprintf("    --%s: %s;\n", D[i], v) }
  print "@media (prefers-color-scheme: dark) {"
  print "  :root:not([data-theme=\"light\"]) {"; printf "%s", out; print "  }"
  print "}"
  print ":root[data-theme=\"dark\"] {"; o2 = out; gsub(/\n    /, "\n  ", o2); sub(/^    /, "  ", o2); printf "%s", o2; print "}"
}'
ASCENT_LIGHT="$1" ASCENT_DARK="${2:-}" LC_ALL=C awk "$PROG" </dev/null
